type I18n = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
  formatCurrency: (amount: number) => string;
  formatDate: (date: string) => string;
  text: (value: Record<string, unknown>, key: string) => string;
};
const I18nContext = createContext<I18n | null>(null);
const storageKey = "elan-language";

export function localizedText(value: Record<string, unknown>, key: string, language: Language) {
  const suffix = language === "ar" ? "Ar" : "En";
  const localized = value[`${key}${suffix}`];
  return typeof localized === "string" ? localized : String(value[key] ?? "");
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    return window.localStorage.getItem(storageKey) === "ar" ? "ar" : "en";
  });
  useLayoutEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    window.localStorage.setItem(storageKey, language);
  }, [language]);
  const value = useMemo<I18n>(
    () => ({
      language,
      setLanguage,
      t: (key) => translations[language][key] ?? translations.en[key] ?? key,
      formatCurrency: (amount) =>
        language === "ar"
          ? `${new Intl.NumberFormat("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount)} د.أ`
          : `JOD ${new Intl.NumberFormat("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount)}`,
      formatDate: (date) =>
        new Intl.DateTimeFormat(language === "ar" ? "ar-JO" : "en-JO", {
          weekday: "short",
          month: "long",
          day: "numeric",
          timeZone: "Asia/Amman",
        }).format(new Date(`${date}T12:00:00+03:00`)),
      text: (item, key) => localizedText(item, key, language),
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
